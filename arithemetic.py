number1 = int(input("Enter first integer: "))
number2 = int(input("Enter second integer: "))

square1 = number1 ** 2
square2 = number2 ** 2

sum_of_squares = square1 + square2
difference_of_squares = square1 - square2

print("Square of first number:", square1)
print("Square of second number:", square2)
print("Sum of their squares:", sum_of_squares)
print("Difference of their squares:", difference_of_squares)